@dataclass
class WriteGate:
    """TIER-2 乘法门 + 持久载体 w。

    Q1 BIO: 突触标记（e）与神经调质（M）的符合门控可塑性——两者同时在场
            才发生持久权重改变（三因子可塑性的物理形态）。
    Q2 PHYS: e→FET_e / M→FET_M 两个真实 MOSFET，各自阈下硬截零（DEG-019）；
            乘积作为 write current 进入 Memristor.update（原语中唯一的
            "写电流→w"入口，semiconductor.py:277-280 Strukov 型）。
            范式先例：theta_comparator.py:170 NMDA 乘法门控（用户 2026-09-06
            裁定"比较完全由物理结构承担"）。
    Q3 PARAM: FET 阈值/跨导取 MOSFET 原语默认（0.3 / 1.0），零自由参数；
            w₀=0.90 由 R-4 冻结；极性见 WRITE_POLARITY。

    LIMITATION（R-2 强制）：见 TIER2_LIMITATION——两个因子由器件产生，但
    合成不是自洽串联节点解。
    """
    fet_e: MOSFET
    fet_m: MOSFET
    bundle: SynapticBundle          # 承载 memristor 并提供未来读出通路
    src: RelationInputNeuron
    dst: Neuron
    i_write_last: float = field(default=0.0, init=False)

    @property
    def mem(self):
        """被写入/读出的同一个 Memristor（bundle 内第 0 条突触）。"""
        return self.bundle._memristors[0][0]

    @property
    def w(self) -> float:
        return self.mem.w

    def write(self, e: float, m: float) -> float:
        """一步写入：I_write = FET_e(e)·FET_M(M) → Memristor.update。

        任一因子阈下 ⇒ 该 FET conduct 精确为 0 ⇒ I_write=0 ⇒ dw=0
        （负例是精确零，非近似——DEG-019 硬截零）。
        """
        i_e = self.fet_e.conduct(e)
        i_m = self.fet_m.conduct(m)
        i_write = i_e * i_m
        self.i_write_last = i_write
        # WRITE_POLARITY=DEPLETION：dw = 0.5·I·(pre−post) = −0.5·I
        self.mem.update(current=i_write, pre_trace=0.0,
                        post_trace=POST_TRACE_UNIT)
        return i_write


def build_write_gate(ident: str = "mfs0_w") -> WriteGate:
    """装配写入门 + 持久载体。

    w₀ 显式设定为 INITIAL_W：`bundle.py:229-235` 会按 crc32(bundle_id:i:j)
    对 initial_weight 施加 ±25% 确定性扰动（多突触对称性打破用），在单突触
    场景无意义且会使实际 w₀ ≠ R-4 冻结值。显式赋值是
    NO_RUNTIME_W0_SEARCH 的兑现，不是运行时寻优。
    """
    src = RelationInputNeuron(f"{ident}_q")
    dst = Neuron(NeuronConfig(
        neuron_id=f"mfs0_readout_{ident}",
        capacitance=C_E, r_leak=R_E,
        inertia=0.0, vdd=2.0, r_supply=0.01, spiking=False))
    bundle = SynapticBundle(
        config=BundleConfig(
            bundle_id=f"mfs0_persist_{ident}",
            learning_rule="frozen",      # 不走 bundle.learn()（方案 §7）
            initial_weight=INITIAL_W,
            weight_max=1.0, weight_min=0.0,
            synapse_gain=1.0,
            bundle_role="feedforward",
            physical_seed=91000),        # 同 adapter 共参（S0-bX1 纪律）
        sources=[src], targets=[dst])
    bundle._memristors[0][0].w = INITIAL_W        # 见 docstring
    bundle._memristors[0][0]._w_initial = INITIAL_W
    return WriteGate(MOSFET(v_threshold=FET_V_THRESHOLD, gm=FET_GM),
                     MOSFET(v_threshold=FET_V_THRESHOLD, gm=FET_GM),
                     bundle, src, dst)


