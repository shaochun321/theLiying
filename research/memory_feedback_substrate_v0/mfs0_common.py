def assert_paths_independent(elig, modu) -> None:
    """守卫 R-1：Past→e 与 Later→M 两条链对象级不相交（禁 W→H_τ^Δ）。"""
    e_objs = {id(elig.tin), id(elig.bundle), id(elig.cell)}
    m_objs = {id(modu.adapter), id(modu.adapter.input_neuron),
              id(modu.adapter.collector), id(modu.adapter.bundle),
              id(modu.gate), id(modu.kernel)}
    overlap = e_objs & m_objs
    if overlap:
        raise AssertionError(
            f"PATH_INDEPENDENCE_VIOLATION: e 链与 M 链共享对象 {overlap}"
            "（R-1：M 可能只是 e 的重复编码）")


