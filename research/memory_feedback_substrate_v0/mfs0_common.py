@dataclass
class EligibilityParts:
    """e 链的物理对象（全部既有 production 原语）。"""
    tin: RelationInputNeuron
    bundle: SynapticBundle
    cell: Neuron

    @property
    def e(self) -> float:
        """canonical eligibility 读出 = 电容电压（方案 §4.4；非 activation）。"""
        return self.cell._membrane.voltage      # DIAGNOSTIC_READ（只读）

    @property
    def e_activation(self) -> float:
        """DIAGNOSTIC_ONLY：过 MOSFET 后的读出，阈下硬截零（DEG-019）。"""
        return self.cell.activation


def build_eligibility(ident: str = "mfs0_e") -> EligibilityParts:
    """χ_ρ^(1) → I_e → C_e 的物理装配。

    Q1 BIO: 突触标记 / 残余 Ca²⁺——一次关系发生在突触留下有限时长的
            "可修改资格"（REF: Zucker & Regehr 2002；项目内同引用链见
            history_kernel.py Q1 与 compensation.py CalciumRateIntegrator）。
    Q2 PHYS: RelationOccurrencePortV1 → build_phase_drive → RelationInputNeuron
            （HC-009 换能先例）→ frozen SynapticBundle → Neuron(_membrane
            = Capacitor)。Sources/Targets 全是真实 Neuron 对象，无变量注入。
    Q3 PARAM: C_E/R_E 见 TAU_E_BASIS；换能束参数继承
            make_relation_transducer_bundle（w=0.3 frozen / gain=1.0 /
            physical_seed=91000，relation_event_adapter.py Q3）。
    """
    tin = RelationInputNeuron(ident)
    cell = Neuron(NeuronConfig(
        neuron_id=f"mfs0_eligibility_cap_{ident}",
        capacitance=C_E, r_leak=R_E,       # τ_e = R·C = 0.300 s
        inertia=0.0, vdd=2.0, r_supply=0.01, spiking=False))
    bundle = make_relation_transducer_bundle(ident, tin, cell)
    return EligibilityParts(tin, bundle, cell)


def step_eligibility(p: EligibilityParts, theta: float,
                     dt: float = DT_G) -> float:
    """推进一步，返回 canonical e = V_{C_e}。theta = build_phase_drive 的 ϑ。"""
    p.tin.step(theta, dt)
    currents = p.bundle.propagate()
    p.cell.step(currents[0] if currents else 0.0, dt)
    return p.e


