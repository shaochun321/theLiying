def fit_tau(vs: Sequence[float], k0: int, dt: float = DT_G,
            floor: float = EPSILON_NUM) -> float:
    """对自由衰减段做 ln 线性拟合，返回实测 τ（秒）。

    只取 k0 之后、值仍高于 floor 的单调下降段——RC 自由衰减的精确指数
    （Capacitor.leak）保证 ln V 对 t 严格线性。
    """
    ks, ys = [], []
    for k in range(k0, len(vs)):
        v = vs[k]
        if v <= floor:
            break
        if ks and v > vs[ks[-1]]:
            break
        ks.append(k)
        ys.append(math.log(v))
    if len(ks) < 3:
        return float('nan')
    n = len(ks)
    mx = sum(ks) / n
    my = sum(ys) / n
    num = sum((ks[i] - mx) * (ys[i] - my) for i in range(n))
    den = sum((ks[i] - mx) ** 2 for i in range(n))
    slope = num / den if den else float('nan')
    return -1.0 / (slope / dt) if slope else float('nan')


def last_above(vs: Sequence[float], thr: float) -> int:
    """最后一个 > thr 的步号；全程不超过返回 -1。"""
    for k in range(len(vs) - 1, -1, -1):
        if vs[k] > thr:
            return k
    return -1


def window_above(vs: Sequence[float], thr: float) -> Tuple[int, int]:
    """[首个 > thr, 最后一个 > thr]；不存在返回 (-1,-1)。"""
    first = -1
    for k, v in enumerate(vs):
        if v > thr:
            first = k
            break
    return (first, last_above(vs, thr))


def conductance(w: float, r_min: float = 0.1, r_max: float = 10.0) -> float:
    """G(w) = 1/(r_min + (r_max−r_min)(1−w))，与 Memristor 原语同式。"""
    return 1.0 / max(r_min + (r_max - r_min) * (1.0 - w), r_min)


