def build_modulation(ident: str = "mfs0_m_delta") -> ModulationParts:
    """Δ → 换能 → spiking collector → E^↑ → H_τ^Δ → M 的物理装配。

    Q1 BIO: later occurrence 在局部留下的进入历史痕（同 H_τ 的 Q1：
            突触前残余 Ca²⁺ / 短时程易化）。**无 valence**——不表示
            reward/punishment/success/failure（方案 §5/§6）。
    Q2 PHYS: RelationEventAdapter（换能→frozen 束→spiking collector→
            CollectorBoundaryPort，HC-009 拓扑 A）→ PhysicalEntryGate
            （b^↑，每枚 spike 刷新 + Zener 钳位）→ PhysicalHistoryKernel
            （τ_h=0.6 s RC 历史池）。三件套默认参数零改动。
    Q3 PARAM: 全部继承既有冻结值（adapter Q3 / entry_gate Q3 / history_kernel
            Q3），本轮零新参数。τ_M = τ_h = 0.600 s。

    R-1 独立性：本实例的输入端口只接 Δ 的 site23 窗，地址父节点为 site23
    生成元，与 W 的 relation port 无任何共享对象（assert_paths_independent）。
    """
    reg = AddressRegistry()
    _rho2, _rho, addr_c = relation2_address()
    # 谱系父 = (site23 生成元, site23 生成元)：本实例完全源自 Δ 侧，
    # 不含 W/ρ 的地址——R-1 "独立地址" 的结构兑现。
    adapter = RelationEventAdapter(reg, addr_c, addr_c, ident)
    gate = PhysicalEntryGate(generator_address=adapter.generator_address)
    kernel = PhysicalHistoryKernel(generator_address=gate.generator_address)
    return ModulationParts(adapter, gate, kernel)


def step_modulation(p: ModulationParts, theta: float,
                    dt: float = DT_G) -> float:
    """推进一步，返回 M(t)。theta = Δ 侧 build_phase_drive 的 ϑ。"""
    spike = p.adapter.step(theta, dt)
    b_up = p.gate.step(spike, dt)
    p._m = p.kernel.step(b_up, dt)
    return p._m


